  /* اقتراحات من كتالوج الخادم (بعد المزامنة): تُخزَّن في هذا الكائن */
  const REMOTE = {};
  function setRemote(map) {
    Object.keys(REMOTE).forEach((k) => delete REMOTE[k]);
    Object.keys(map || {}).forEach((k) => { REMOTE[k] = (map[k] || []).map((x) => ({ name: x.name, kind: x.kind || 'core' })); });
  }

  function lookup(sel, product) {
    const key = (product && product.ingKey) || (sel && sel.productId) || null;
    // أولوية: اقتراحات الخادم لمنتج/نشاط محددين، ثم القاعدة المحلية
    if (key && REMOTE[key] && REMOTE[key].length) return { source: 'server', items: REMOTE[key] };
    if (sel && sel.domainId && REMOTE['domain:' + sel.domainId] && REMOTE['domain:' + sel.domainId].length) {
      return { source: 'server-domain', items: REMOTE['domain:' + sel.domainId] };
    }
    let list = key && CATALOG[key] ? CATALOG[key] : null;
    let source = 'product';
    if (!list && sel && BY_SUBCATEGORY[sel.subcategoryId]) { list = CATALOG[BY_SUBCATEGORY[sel.subcategoryId]] || null; source = 'subcategory'; }
    if (!list && sel && BY_DOMAIN[sel.domainId]) { list = BY_DOMAIN[sel.domainId]; source = 'domain'; }
    if (!list) { list = BY_DOMAIN.saudi_food; source = 'fallback'; }
    return { source, items: parse(list) };
  }

  // بحث نصّي داخل كل القاعدة (للاقتراحات عند الكتابة)
  function search(term, limit) {
    const q = String(term || '').trim();
    if (!q) return [];
    const seen = new Map();
    Object.keys(CATALOG).forEach((k) => {
      parse(CATALOG[k]).forEach((x) => {
        if (x.name.indexOf(q) > -1 && !seen.has(x.name)) seen.set(x.name, x.kind);
      });
    });
    return Array.from(seen.entries()).slice(0, limit || 8).map(([name, kind]) => ({ name, kind }));
  }

